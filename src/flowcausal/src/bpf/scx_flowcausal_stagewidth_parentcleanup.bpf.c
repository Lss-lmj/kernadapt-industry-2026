/*
 * FlowCausal-StageWidth-ParentCleanup.
 *
 * Dynamically accelerate the harness supervisor only after a tracked child has
 * exited.  Unlike ParentBoost, the parent does not become a frontier task; it
 * repeatedly uses the latency DSQ for a short cleanup window so wait/cleanup
 * continuation can finish without permanently competing with BUILD/TEST
 * frontiers.
 */
