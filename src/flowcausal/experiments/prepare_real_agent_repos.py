#!/usr/bin/env python3
"""Generate or run per-instance repository preparation for real-agent plans.

``plan_real_agent_instances.py`` chooses benchmark instances and records where
their replay repositories should live.  This helper turns that plan into a
reproducible repo-preparation artifact:

* a shell script that clones/fetches each repository;
* optional checkout to the task's ``base_commit``;
* a JSON/Markdown manifest documenting URLs, commits, warnings, and blockers.

The default is generate-only.  Use ``--execute`` only when you intentionally
want to clone/fetch repositories.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import shlex
import shutil
import subprocess
from typing import Any


SCHEMA = "flowcausal.real_agent_repo_preparation.v1"


def as_dict(value: Any) -> dict[str, Any]:
    return value if isinstance(value, dict) else {}


def as_list(value: Any) -> list[Any]:
    return value if isinstance(value, list) else []


def sh(value: str | pathlib.Path) -> str:
    return shlex.quote(str(value))


def read_json(path: pathlib.Path) -> dict[str, Any]:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise SystemExit(f"invalid JSON at {path}: {exc}") from exc
    if not isinstance(data, dict):
        raise SystemExit(f"plan is not a JSON object: {path}")
    return data


def repo_url(repo: str) -> str:
    text = repo.strip()
    if text.startswith(("https://", "http://", "ssh://", "git@")):
        return text
    if "/" in text and not text.endswith(".git"):
        return f"https://github.com/{text}.git"
    if "/" in text:
        return f"https://github.com/{text}"
    return text


def base_commit(row: dict[str, Any]) -> str:
    raw = as_dict(row.get("raw"))
    for key in ("base_commit", "commit", "base_sha", "base_ref"):
        value = raw.get(key) or row.get(key)
        if isinstance(value, str) and value.strip():
            return value.strip()
    return ""


def row_repo_dir(row: dict[str, Any], repo_root: pathlib.Path | None) -> pathlib.Path:
    if repo_root is not None:
        instance_id = str(row.get("instance_id") or "").strip()
        safe = "".join(ch if ch.isalnum() or ch in {"-", "_", "."} else "-" for ch in instance_id).strip("-") or "instance"
        return repo_root / safe
    value = str(row.get("repo_dir") or "").strip()
    if not value:
        instance_id = str(row.get("instance_id") or "").strip() or "instance"
        return pathlib.Path("benchmarks/harness-replaybench/repos") / instance_id
    return pathlib.Path(value)


def script_lines(rows: list[dict[str, Any]], *, git: str) -> list[str]:
    lines = [
        "#!/usr/bin/env bash",
        "set -euo pipefail",
        "",
        "# Generated by prepare_real_agent_repos.py.",
        "",
    ]
    for row in rows:
        repo_dir = pathlib.Path(str(row["repo_dir"]))
        lines.extend(
            [
                f"# {row['instance_id']} {row['repo']}",
                f"mkdir -p {sh(repo_dir.parent)}",
                f"if [ ! -d {sh(repo_dir / '.git')} ]; then {sh(git)} clone --filter=blob:none {sh(row['repo_url'])} {sh(repo_dir)}; fi",
                f"{sh(git)} -C {sh(repo_dir)} fetch --all --tags --prune",
            ]
        )
        if row.get("base_commit"):
            lines.append(f"{sh(git)} -C {sh(repo_dir)} checkout --detach {sh(row['base_commit'])}")
        else:
            lines.append(f"echo 'WARNING: {row['instance_id']} has no base_commit; leaving repository at current HEAD' >&2")
        lines.extend(
            [
                f"{sh(git)} -C {sh(repo_dir)} rev-parse HEAD > {sh(repo_dir / '.flowcausal-head')}",
                "",
            ]
        )
    return lines


def build_report(args: argparse.Namespace) -> dict[str, Any]:
    plan_path = pathlib.Path(args.plan).expanduser().resolve()
    plan = read_json(plan_path)
    if plan.get("schema") != "flowcausal.real_agent_instance_plan.v1":
        raise SystemExit(f"unexpected plan schema: {plan.get('schema')!r}")
    selected = [row for row in as_list(plan.get("selected")) if isinstance(row, dict)]
    repo_root = pathlib.Path(args.repo_root).expanduser().resolve() if args.repo_root else None
    rows: list[dict[str, Any]] = []
    warnings: list[str] = []
    blockers: list[str] = []
    seen_dirs: set[str] = set()
    for row in selected:
        instance_id = str(row.get("instance_id") or "").strip()
        repo = str(row.get("repo") or "").strip()
        if not instance_id or not repo:
            blockers.append(f"selected row missing instance_id/repo: {row}")
            continue
        repo_dir = row_repo_dir(row, repo_root)
        commit = base_commit(row)
        if not commit:
            warnings.append(f"{instance_id}: missing base_commit; checkout is not pinned")
        repo_dir_text = str(repo_dir)
        if repo_dir_text in seen_dirs:
            blockers.append(f"duplicate repo_dir in plan: {repo_dir_text}")
        seen_dirs.add(repo_dir_text)
        rows.append(
            {
                "instance_id": instance_id,
                "repo": repo,
                "repo_url": repo_url(repo),
                "repo_dir": repo_dir_text,
                "base_commit": commit,
            }
        )
    if not rows:
        blockers.append("plan has no selected rows with instance_id and repo")
    git_path = pathlib.Path(args.git)
    if (git_path.is_absolute() or "/" in args.git) and not git_path.exists():
        blockers.append(f"--git executable does not exist: {args.git}")
    elif not git_path.is_absolute() and "/" not in args.git and shutil.which(args.git) is None:
        blockers.append(f"--git executable was not found in PATH: {args.git}")
    status = "pass" if not blockers else "partial" if rows else "fail"
    return {
        "schema": SCHEMA,
        "status": status,
        "plan": str(plan_path),
        "summary": {
            "selected_instances": len(selected),
            "repo_rows": len(rows),
            "missing_base_commit": sum(1 for row in rows if not row.get("base_commit")),
        },
        "repos": rows,
        "warnings": warnings,
        "blockers": blockers,
        "notes": [
            "repo preparation is not performance evidence; it only pins replay inputs",
            "missing base_commit means the repo version is not reproducibly pinned",
        ],
    }


def markdown(report: dict[str, Any]) -> str:
    lines = [
        "# FlowCausal real-agent repo preparation",
        "",
        f"Status: `{report.get('status')}`",
        "",
        "| Instance | Repo | Base commit | Repo dir |",
        "| --- | --- | --- | --- |",
    ]
    for row in as_list(report.get("repos")):
        if not isinstance(row, dict):
            continue
        lines.append(
            f"| `{row.get('instance_id', '')}` | `{row.get('repo', '')}` | `{row.get('base_commit', '')}` | `{row.get('repo_dir', '')}` |"
        )
    if report.get("warnings"):
        lines.extend(["", "## Warnings", ""])
        for item in as_list(report.get("warnings")):
            lines.append(f"- {item}")
    if report.get("blockers"):
        lines.extend(["", "## Blockers", ""])
        for item in as_list(report.get("blockers")):
            lines.append(f"- {item}")
    return "\n".join(lines) + "\n"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate or run repo preparation for selected real-agent instances",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("--plan", required=True, help="JSON plan from plan_real_agent_instances.py")
    parser.add_argument("--repo-root", help="override repo root; defaults to repo_dir recorded in plan")
    parser.add_argument("--git", default="git")
    parser.add_argument("--output", required=True)
    parser.add_argument("--markdown-output")
    parser.add_argument("--script-output", required=True)
    parser.add_argument("--execute", action="store_true", help="run the generated clone/checkout script")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    report = build_report(args)
    script_path = pathlib.Path(args.script_output).expanduser().resolve()
    output = pathlib.Path(args.output).expanduser().resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    script_path.parent.mkdir(parents=True, exist_ok=True)
    script_path.write_text("\n".join(script_lines(as_list(report.get("repos")), git=args.git)) + "\n", encoding="utf-8")
    script_path.chmod(script_path.stat().st_mode | 0o111)
    run: dict[str, Any] | None = None
    if args.execute and not report.get("blockers"):
        proc = subprocess.run([str(script_path)], stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, check=False)
        run = {
            "returncode": proc.returncode,
            "stdout_tail": proc.stdout[-4000:],
            "stderr_tail": proc.stderr[-4000:],
        }
        if proc.returncode != 0:
            report.setdefault("blockers", []).append(f"repo preparation script failed with returncode={proc.returncode}")
            report["status"] = "partial" if report.get("repos") else "fail"
    elif args.execute and report.get("blockers"):
        run = {"skipped": "not executed because repo preparation blockers exist"}
    report["script"] = str(script_path)
    report["run"] = run
    output.write_text(json.dumps(report, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    if args.markdown_output:
        md = pathlib.Path(args.markdown_output).expanduser().resolve()
        md.parent.mkdir(parents=True, exist_ok=True)
        md.write_text(markdown(report), encoding="utf-8")
    print(json.dumps({"status": report["status"], "repos": len(report.get("repos", [])), "output": str(output)}, sort_keys=True))
    return 0 if report["status"] != "fail" else 1


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except KeyboardInterrupt:
        raise SystemExit(130)
