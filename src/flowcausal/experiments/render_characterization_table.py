#!/usr/bin/env python3
"""Render FlowCausal characterization summaries as a paper table.

The characterization harness is intentionally scheduler-free.  This renderer
keeps that evidence boundary visible in the paper by generating a compact
table from one or more ``summary.json`` files instead of hand-copying numbers.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
from typing import Any


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate a LaTeX table from FlowCausal characterization summaries",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--summary",
        nargs="+",
        required=True,
        help="one or more experiments/results/.../summary.json files",
    )
    parser.add_argument("--out", required=True, help="output .tex file")
    return parser.parse_args()


def latex_escape(text: str) -> str:
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    return "".join(replacements.get(ch, ch) for ch in text)


def short_trace_name(summary_path: pathlib.Path, summary: dict[str, Any]) -> str:
    manifest = summary.get("manifest", {})
    out_dir = pathlib.Path(str(manifest.get("out_dir") or summary_path.parent))
    name = out_dir.name
    name = re.sub(r"^characterize-", "", name)
    name = re.sub(r"-smoke$", "", name)
    name = name.replace("buildtest", "build/test")
    return name.replace("-", " ")


def short_level(level: str) -> str:
    match = re.match(r"^(C[0-9.]+)", level)
    return match.group(1) if match else level


def ratio(num: int | None, den: int | None) -> str:
    return f"{int(num or 0)}/{int(den or 0)}"


def share(value: Any) -> str:
    if value is None:
        return "--"
    return f"{float(value):.2f}"


def ms(value_ns: Any) -> str:
    return f"{float(value_ns or 0) / 1_000_000.0:.1f}"


def render_row(summary_path: pathlib.Path) -> str:
    summary = json.loads(summary_path.read_text(encoding="utf-8"))
    sample_count = int(summary.get("sample_count", 0))
    totals = summary.get("aggregate_delta", {})
    row = [
        latex_escape(short_trace_name(summary_path, summary)),
        latex_escape(short_level(str(summary.get("characterization_level", "")))),
        ratio(summary.get("samples_with_frontier"), sample_count),
        f"P{int(summary.get('samples_with_parent_wait', 0))}/B{int(summary.get('samples_with_barrier_tail', 0))}",
        ratio(summary.get("samples_with_schedstat"), sample_count),
        f"{int(summary.get('max_process_count', 0))}/{int(summary.get('max_leaf_count', 0))}",
        f"{share(summary.get('frontier_wait_share'))}/{share(summary.get('frontier_runtime_share'))}",
        f"{ms(totals.get('sched_wait_delta_ns'))}/{ms(totals.get('sched_runtime_delta_ns'))}",
    ]
    return " & ".join(row) + r" \\"


def main() -> int:
    args = parse_args()
    summary_paths = [pathlib.Path(path) for path in args.summary]
    out_path = pathlib.Path(args.out)
    rows = [render_row(path) for path in summary_paths]
    source_list = ", ".join(str(path) for path in summary_paths)
    body = "\n".join(rows)

    table = rf"""% Generated by experiments/render_characterization_table.py
% Sources: {source_list}
\begin{{table*}}[t]
  \centering
  \caption{{Scheduler-free sandbox characterization.  \emph{{Frontier}} is the
  fraction of samples with selected frontier candidates; \emph{{Evidence}} reports
  parent-wait (P) and barrier-tail (B) samples; \emph{{Width}} is max
  processes/leaves; \emph{{Frontier share}} is wait/runtime share.  These rows are
  Go/No-Go characterization inputs, not scheduling speedup results.}}
  \label{{tab:characterization_gate}}
  \small
  \setlength{{\tabcolsep}}{{5pt}}
  \resizebox{{0.92\textwidth}}{{!}}{{%
  \begin{{tabular}}{{llcccccc}}
    \toprule
    Trace & Level & Frontier & Evidence & schedstat & Width & Frontier share & wait/run ms \\
    \midrule
    {body}
    \bottomrule
  \end{{tabular}}%
  }}
  \vspace{{-0.7em}}
\end{{table*}}
"""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(table, encoding="utf-8")
    print(f"wrote={out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
